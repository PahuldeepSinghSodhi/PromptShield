"""Generate the EDA and error-analysis notebooks (executed by nbconvert afterwards)."""

from pathlib import Path

import nbformat as nbf

ROOT = Path(__file__).resolve().parents[1]
NB = ROOT / "notebooks"


def md(s):
    return nbf.v4.new_markdown_cell(s.strip())


def code(s):
    return nbf.v4.new_code_cell(s.strip())


SETUP = """
import json
from collections import Counter
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path.cwd().parent if Path.cwd().name == "notebooks" else Path.cwd()
FIG = ROOT / "reports" / "figures"
FIG.mkdir(parents=True, exist_ok=True)
plt.rcParams.update({"figure.dpi": 110, "axes.spines.top": False, "axes.spines.right": False})
"""

eda = nbf.v4.new_notebook()
eda.cells = [
    md("""
# 01 · Exploratory data analysis

What the NER and secret-detector training data looks like after the pipeline in
`src/promptshield/data/` (ingest → label unification → synthetic data → cleaning →
validation → grouped split).
"""),
    code(SETUP),
    code("""
ner = pd.read_parquet(ROOT / "data/processed/ner.parquet")
sec = pd.read_parquet(ROOT / "data/processed/secrets.parquet")
report = json.loads((ROOT / "reports/data_quality.json").read_text())
print(f"NER rows: {len(ner):,}   secret texts: {len(sec):,}")
pd.crosstab(ner["source"], ner["split"], margins=True)
"""),
    md("## Entity label distribution (unified labels)"),
    code("""
counts = Counter(s["label"] for spans in ner["spans"] for s in spans)
s = pd.Series(counts).sort_values()
ax = s.plot.barh(color="#2f5bea", figsize=(7, 4))
ax.set_xlabel("entities"); ax.set_title("Entities per unified label")
for i, v in enumerate(s.values):
    ax.text(v, i, f" {v:,}", va="center", fontsize=8)
plt.tight_layout(); plt.savefig(FIG / "entity_distribution.png"); plt.show()
"""),
    md("CREDENTIAL and DATE are the rarest labels, which is why the PyTorch loss uses softened inverse-frequency class weights."),
    md("## Text length and entity density by source"),
    code("""
ner["chars"] = ner["text"].str.len()
ner["n_entities"] = ner["spans"].str.len()
fig, axes = plt.subplots(1, 2, figsize=(10, 3.5))
for src, g in ner.groupby("source"):
    axes[0].hist(g["chars"], bins=60, alpha=0.6, label=src, density=True)
    axes[1].hist(g["n_entities"], bins=range(0, 15), alpha=0.6, label=src, density=True)
axes[0].set_title("characters per row"); axes[1].set_title("entities per row")
axes[0].legend(); plt.tight_layout(); plt.savefig(FIG / "lengths.png"); plt.show()
ner.groupby("source")[["chars", "n_entities"]].describe().round(1)
"""),
    md("## Data quality report\n\nGenerated by `data/build.py`; pandera schema and leakage checks passed before this file was written."),
    code("""
{k: v for k, v in report.items() if k not in ("entity_counts", "text_len_chars")}
"""),
    md("## Secret-detector data\n\nPositives are fake credentials in real formats; negatives are look-alikes (hashes, UUIDs, placeholders, env-var names, IDs)."),
    code("""
sec["kind_group"] = np.where(sec["label"] == 1, "secret", "look-alike")
print(sec["label"].value_counts(normalize=True).round(3))
sec.groupby(["split", "kind_group"]).size().unstack()
"""),
]

err = nbf.v4.new_notebook()
err.cells = [
    md("""
# 02 · Model comparison and error analysis

scikit-learn token baseline vs fine-tuned DistilBERT, per-entity results, and the
inference backends (PyTorch / ONNX FP32 / ONNX INT8).
"""),
    code(SETUP),
    code("""
ner_m = json.loads((ROOT / "reports/ner_metrics.json").read_text())
sk_m = json.loads((ROOT / "reports/sk_token_baseline_metrics.json").read_text())
sec_m = json.loads((ROOT / "reports/secret_detector_metrics.json").read_text())
overall = pd.DataFrame({
    "sklearn baseline (LogReg, handcrafted features)": {k: sk_m["test"][k] for k in ("precision", "recall", "f1")},
    "DistilBERT fine-tuned (PyTorch)": {k: ner_m["test"][k] for k in ("precision", "recall", "f1")},
}).T
overall
"""),
    code("""
labels = [k for k in ner_m["test"]["per_entity"] if k.isupper()]
per = pd.DataFrame({
    "sklearn": {l: sk_m["test"]["per_entity"][l]["f1-score"] for l in labels},
    "DistilBERT": {l: ner_m["test"]["per_entity"][l]["f1-score"] for l in labels},
}).sort_values("DistilBERT")
ax = per.plot.barh(figsize=(7, 4.5), color=["#9aa5b4", "#2f5bea"])
ax.set_xlabel("entity-level F1 (test)"); ax.set_xlim(0, 1); ax.set_title("Per-entity F1")
plt.tight_layout(); plt.savefig(FIG / "per_entity_f1.png"); plt.show()
per.round(3)
"""),
    md("## Calibration\n\nTemperature scaling fitted on validation logits; ECE measured on test tokens."),
    code("ner_m['calibration']"),
    md("## Secret detector: in-distribution vs out-of-distribution"),
    code("""
rows = {}
for name, m in sec_m["models"].items():
    for part in ("test", "challenge_ood"):
        rows[(name, part)] = {k: m[part][k] for k in ("precision", "recall", "f1", "average_precision")}
pd.DataFrame(rows).T
"""),
    md("""
The challenge set uses contexts and token formats that never appear in training
(e.g. GitLab `glpat-` tokens, keyword-free credentials). Remaining misses are
mostly 32-char hex secrets with no keyword nearby, which are indistinguishable
from MD5 hashes without context: a documented limitation.
"""),
    md("## Inference backends"),
    code("""
bench = json.loads((ROOT / "reports/benchmark.json").read_text())
pd.DataFrame(bench["summary"]).T
"""),
    code("""
lat = pd.DataFrame([
    {"backend": b, "batch": l["batch"], "p95_ms": l["p95_ms"]}
    for b, r in bench["details"].items() for l in r["latency"]
]).pivot(index="batch", columns="backend", values="p95_ms")
ax = lat.plot.bar(figsize=(7, 3.5), color=["#2f5bea", "#9aa5b4", "#1f8a4c"])
ax.set_ylabel("p95 latency per call (ms)"); ax.set_title("CPU latency by backend and batch size")
plt.xticks(rotation=0); plt.tight_layout(); plt.savefig(FIG / "latency.png"); plt.show()
lat
"""),
]

NB.mkdir(exist_ok=True)
nbf.write(eda, NB / "01_eda.ipynb")
nbf.write(err, NB / "02_error_analysis.ipynb")
print("notebooks written")
